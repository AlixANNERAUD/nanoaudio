use super::{Encoding, Location, Text};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Id3v1<'a> {
    pub title: Text<'a>,
    pub artist: Text<'a>,
    pub album: Text<'a>,
    pub year: Text<'a>,
    pub comment: Text<'a>,
    pub track: Option<u8>,
    pub genre: Option<u8>,
}

impl<'a> Id3v1<'a> {
    pub const LENGTH: usize = 128;

    pub const fn location(file_length: usize) -> Option<Location> {
        match file_length.checked_sub(Self::LENGTH) {
            Some(offset) => Some(Location::new(offset, Self::LENGTH)),
            None => None,
        }
    }

    pub fn parse(bytes: &'a [u8]) -> Option<Self> {
        let start = bytes.len().checked_sub(Self::LENGTH)?;
        let tag = &bytes[start..];

        if &tag[..3] != b"TAG" {
            return None;
        }

        let comment = &tag[97..127];
        let (comment, track) = match (comment[28], comment[29]) {
            (0, 0) => (&comment[..28], None),
            (0, track) => (&comment[..28], Some(track)),
            _ => (comment, None),
        };

        Some(Self {
            title: field(&tag[3..33]),
            artist: field(&tag[33..63]),
            album: field(&tag[63..93]),
            year: field(&tag[93..97]),
            comment: field(comment),
            track,
            genre: match tag[127] {
                255 => None,
                genre => Some(genre),
            },
        })
    }

    pub fn genre_name(&self) -> Option<&'static str> {
        genre(self.genre?)
    }
}

fn field(bytes: &[u8]) -> Text<'_> {
    let end = bytes
        .iter()
        .position(|byte| *byte == 0)
        .unwrap_or(bytes.len());

    Text::new(Encoding::Latin1, bytes[..end].trim_ascii())
}

pub fn genre(index: u8) -> Option<&'static str> {
    GENRES.get(index as usize).copied()
}

